import { createHash } from 'node:crypto';
import { defineConfig, type Plugin } from 'vite';

/**
 * Emits sw.js, a service worker that caches the built app so it works offline
 * after its first load. It caches only the app's own files, never documents.
 */
function serviceWorker(): Plugin {
  return {
    name: 'dotwright-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      // Relative to sw.js, which sits beside index.html, so the site can live in any folder.
      const files = ['./', ...Object.keys(bundle).map((f) => './' + f)];
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts.
const CACHE = 'dotwright-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== location.origin) return;
  if (request.mode === 'navigate') {
    // Prefer a fresh page; fall back to the cached app when offline.
    event.respondWith(fetch(request).catch(() => caches.match(new URL('./', location.href))));
    return;
  }
  // Module scripts and the preloaded font are requested with an Origin header the cached copies lack.
  event.respondWith(caches.match(request, { ignoreVary: true }).then((cached) => cached || fetch(request)));
});
`,
      });
    },
  };
}

export default defineConfig({
  // Relative URLs, so the built site works from any folder of a website.
  base: './',
  plugins: [serviceWorker()],
});
